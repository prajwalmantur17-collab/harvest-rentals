const dicts: Record<Lang, Dict> = { en, kn, hi };
export const LANGS: { code: Lang; label: string }[] = [
  { code: 'en', label: 'English' }, { code: 'kn', label: 'ಕನ್ನಡ' }, { code: 'hi', label: 'हिन्दी' },
];
const KEY = 'harvest-rentals-lang';

interface Ctx { lang: Lang; setLang: (l: Lang) => void; t: (k: keyof Dict, vars?: Record<string, string | number>) => string }
const I18nContext = createContext<Ctx | null>(null);

function initialLang(): Lang {
  try {
    const v = localStorage.getItem(KEY);
    if (v === 'en' || v === 'kn' || v === 'hi') return v;
  } catch { /* storage blocked: use default */ }
  return 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem(KEY, l); } catch { /* ignore */ }
  };
  const t: Ctx['t'] = (k, vars) => {
    let s = dicts[lang][k];
    if (vars) for (const [n, v] of Object.entries(vars)) s = s.replace(`{${n}}`, String(v));
    return s;
  };
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const c = useContext(I18nContext);
  if (!c) throw new Error('I18nProvider missing');
  return c;
}
